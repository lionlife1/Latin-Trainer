import type { Adjective } from '../../src/lib/morph/adjectives';
import type { LexiconRow } from '../build-seed';
import { lemmaKey } from './compose';
import { clipGloss, firstSense } from './gloss';
import { freqRank, matchHeadword } from './match';
import { dictlineFields, have } from './whitaker';

export interface WhitakerAdjective {
  adjective: Omit<Adjective, 'trans'>;
  /** Spellings of the 2nd headword part this line allows ("bona", "acris" and "acre"). */
  keys: string[];
  freq: string;
  /** 0-based line in DICTLINE.GEN; the earlier line wins a frequency tie. */
  line: number;
}

/** Irregular comparison Whitaker doesn't encode as stems, by nominative. */
const COMPARISON_FIXES: Record<string, { comp: string; sup: string }> = {
  malus: { comp: 'pei', sup: 'pessi' },
  multus: { comp: 'plur', sup: 'pluri' },
};

/** Other per-word corrections Whitaker's codes get wrong, by nominative. */
const ADJECTIVE_FIXES: Record<string, Partial<Adjective>> = {
  iuvenis: { terminations: 1 },
};

/** Separate headwords that duplicate another adjective's comparative (plus, pluris is multus). */
const EXCLUDED = new Set(['plus']);

/** Whitaker lists these as i-stems, but they decline with consonant-stem endings. */
const CONSONANT_ADJ = new Set(['vetus', 'pauper', 'dives', 'princeps', 'particeps', 'compos', 'superstes', 'senex', 'memor', 'uber', 'pubes', 'iuvenis']);

function adjectiveFromLine(line: string): Omit<WhitakerAdjective, 'line'> | null {
  const d = dictlineFields(line);
  if (!d || d.f[0] !== 'ADJ') return null;
  const [s1, s2raw, s3, s4] = d.s.map(x => x.toLowerCase().replace(/j/g, 'i'));
  if (!have(s1)) return null;
  const s2 = have(s2raw) ? s2raw : s1;
  const code = `${d.f[1]} ${d.f[2]}`;
  const mk = (nom: string, decl: Adjective['decl'], keys: string[], extra: Partial<Adjective> = {}) => {
    const adjective: Omit<Adjective, 'trans'> = { nom, stem: s2, decl, ...extra };
    const fix = COMPARISON_FIXES[nom];
    Object.assign(adjective, ADJECTIVE_FIXES[nom]);
    if (fix) Object.assign(adjective, fix);
    else if (d.f[3] === 'X' && have(s3) && have(s4)) Object.assign(adjective, { comp: s3, sup: s4 });
    if (CONSONANT_ADJ.has(nom)) adjective.consonantStem = true;
    return { adjective, keys, freq: d.freq };
  };
  switch (code) {
    case '1 1': return mk(s1 + 'us', '12', [s2 + 'a']);
    case '1 2': return mk(s1, '12', [s2 + 'a']);
    case '1 3': case '1 5': return mk(s1 + 'us', '12', [s2 + 'a'], { pronominal: true });
    case '1 4': return mk(s1, '12', [s2 + 'a'], { pronominal: true });
    case '3 1': return mk(s1, '3', [s2 + 'is'], { terminations: 1 });
    case '3 2': return mk(s1 + 'is', '3', [s2 + 'e'], { terminations: 2 });
    case '3 3': return mk(s1, '3', [s2 + 'is', s2 + 'e'], { terminations: 3 });
    default: return null;
  }
}

/** Every drillable adjective in DICTLINE, one per nominative, stem and declension (best frequency, then file order). */
export function parseWhitakerAdjectives(dictline: string): WhitakerAdjective[] {
  const best = new Map<string, WhitakerAdjective>();
  dictline.split('\n').forEach((l, line) => {
    const r = adjectiveFromLine(l);
    if (!r) return;
    const a = r.adjective;
    const key = `${a.nom}|${a.stem}|${a.decl}|${a.terminations ?? ''}|${a.pronominal ? 'p' : ''}`;
    const cur = best.get(key);
    if (!cur || freqRank(r.freq) < freqRank(cur.freq)) best.set(key, { ...r, line });
  });
  return [...best.values()];
}

/** Core lexicon adjectives -> trainer adjectives; rows with no matching Whitaker adjective come back as unmatched headwords. */
export function coreAdjectives(rows: LexiconRow[], whitaker: WhitakerAdjective[]): { adjectives: Adjective[]; unmatched: string[] } {
  const adjectives = new Map<string, Adjective>();
  const unmatched: string[] = [];
  for (const r of rows) {
    if (!r.core || r.pos !== 'adjective') continue;
    const match = matchHeadword(r, whitaker, w => w.adjective.nom, w => w.keys);
    if (!match) {
      unmatched.push(r.headword);
      continue;
    }
    if (EXCLUDED.has(lemmaKey(match.adjective.nom))) continue;
    const adjective: Adjective = { ...match.adjective, trans: clipGloss(firstSense(r.definition)) };
    const id = `${adjective.nom}|${adjective.stem}|${adjective.decl}`;
    if (!adjectives.has(id)) adjectives.set(id, adjective);
  }
  return { adjectives: [...adjectives.values()].sort((x, y) => x.nom.localeCompare(y.nom)), unmatched };
}

/** Source of src/content/adjectives.generated.ts. */
export function adjectivesModule(adjectives: Adjective[]): string {
  return [
    '// Generated by scripts/build-seed.ts from the core lexicon adjectives and Whitaker stems. Do not edit by hand.',
    "import type { Adjective } from '../lib/morph/adjectives';",
    '',
    `export const CORE_ADJECTIVES: Adjective[] = [\n${adjectives.map(a => '  ' + JSON.stringify(a)).join(',\n')}\n];`,
    '',
  ].join('\n');
}
