// Generates supabase/seed.sql: built-in modules, questions and the lexicon.
// Lexicon source: content/raw/dcc-core.csv (Dickinson College Commentaries Latin Core Vocabulary, CC BY-SA)
// when present, otherwise content/starter-lexicon.json.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { MODULES } from '../src/content/modules';
import { lemmaOf } from '../src/lib/lexicon';

export { lemmaOf };

export interface LexiconRow {
  headword: string;
  lemma: string;
  definition: string;
  pos: string;
  frequency: number | null;
}

const lit = (v: unknown): string =>
  v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
const json = (v: unknown): string => (v === undefined || v === null ? 'null' : `${lit(JSON.stringify(v))}::jsonb`);

/** Minimal RFC 4180 CSV parser (quoted fields, doubled quotes, CRLF). */
export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { row.push(field); field = ''; }
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i++;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows.filter(r => r.some(c => c.trim()));
}

/** Maps the DCC core list CSV (columns matched by header name) to lexicon rows. */
export function dccToLexicon(csv: string): LexiconRow[] {
  const [header, ...rows] = parseCsv(csv);
  const find = (re: RegExp) => header.findIndex(h => re.test(h.trim()));
  const iHead = find(/^headword$/i), iDef = find(/definition/i), iPos = find(/part of speech/i), iFreq = find(/frequency/i);
  if (iHead < 0 || iDef < 0) throw new Error('DCC CSV needs "Headword" and "Definition" columns');
  return rows.map(r => ({
    headword: r[iHead].trim(),
    lemma: lemmaOf(r[iHead]),
    definition: r[iDef].trim(),
    pos: iPos >= 0 ? r[iPos].trim().toLowerCase() : '',
    frequency: iFreq >= 0 && r[iFreq].trim() ? Number(r[iFreq]) : null,
  }));
}

function main() {
  const dccPath = 'content/raw/dcc-core.csv';
  const lexicon: LexiconRow[] = existsSync(dccPath)
    ? dccToLexicon(readFileSync(dccPath, 'utf8'))
    : JSON.parse(readFileSync('content/starter-lexicon.json', 'utf8'));

  const out: string[] = ['-- Generated by scripts/build-seed.ts. Do not edit by hand.', 'begin;'];
  MODULES.forEach((m, i) => {
    out.push(
      `insert into public.modules (id, badge, title, tagline, description, concepts, sort) values (${lit(m.id)}, ${lit(m.badge)}, ${lit(m.title)}, ${lit(m.tagline)}, ${lit(m.description)}, ${json(m.concepts)}, ${i}) on conflict (id) do update set badge = excluded.badge, title = excluded.title, tagline = excluded.tagline, description = excluded.description, concepts = excluded.concepts, sort = excluded.sort;`,
    );
    m.questions.forEach((q, pos) => {
      const answers = q.type === 'typein' ? json(q.answers) : 'null';
      const choices = q.type === 'mc' ? json(q.choices) : 'null';
      const correct = q.type === 'mc' ? lit(q.correct) : 'null';
      out.push(
        `insert into public.questions (id, module_id, position, type, badge, prompt, hint, answers, choices, correct, explanation) values (${lit(q.id)}, ${lit(m.id)}, ${pos}, ${lit(q.type)}, ${lit(q.badge)}, ${lit(q.prompt)}, ${lit(q.hint)}, ${answers}, ${choices}, ${correct}, ${lit(q.explanation)}) on conflict (id) do update set module_id = excluded.module_id, position = excluded.position, type = excluded.type, badge = excluded.badge, prompt = excluded.prompt, hint = excluded.hint, answers = excluded.answers, choices = excluded.choices, correct = excluded.correct, explanation = excluded.explanation;`,
      );
    });
  });
  out.push('delete from public.lexicon where owner_id is null and id not in (select lexicon_id from public.vocab_list_items);');
  for (const w of lexicon) {
    out.push(
      `insert into public.lexicon (headword, lemma, definition, pos, frequency) select ${lit(w.headword)}, ${lit(w.lemma)}, ${lit(w.definition)}, ${lit(w.pos)}, ${lit(w.frequency)} where not exists (select 1 from public.lexicon where owner_id is null and headword = ${lit(w.headword)} and pos = ${lit(w.pos)});`,
    );
  }
  out.push('commit;', '');
  writeFileSync('supabase/seed.sql', out.join('\n'));
  console.log(`seed.sql: ${MODULES.length} modules, ${MODULES.reduce((n, m) => n + m.questions.length, 0)} questions, ${lexicon.length} lexicon rows`);
}

if (process.argv[1]?.endsWith('build-seed.ts')) main();
