// Generates supabase/seed.sql (modules and questions) and supabase/seed-lexicon.sql (the lexicon).
// Lexicon sources, all under content/sources/:
//   - dooge-latin-english.txt: D'Ooge, Latin-English vocabulary (public domain), with macrons
//   - whitaker/DICTLINE.GEN: William Whitaker's Words dictionary data (open license), no macrons
//   - lodge-core.tsv: Lodge's core list (public domain, numbered alphabetically), which marks the core words
import { readFileSync, writeFileSync } from 'node:fs';
import { MODULES } from '../src/content/modules';
import { lemmaOf } from '../src/lib/lexicon';
import { composeLexicon, parseLodge } from './lexicon/compose';
import { parseDooge } from './lexicon/dooge';
import { adjectivesModule, coreAdjectives, parseWhitakerAdjectives } from './lexicon/adjectives';
import { coreNouns, nounsModule, parseWhitakerNouns } from './lexicon/nouns';
import { coreTrainerVerbs, parseWhitakerVerbs, verbsModule } from './lexicon/verbs';
import { parseDictline } from './lexicon/whitaker';

export { lemmaOf };

export interface LexiconRow {
  headword: string;
  lemma: string;
  definition: string;
  pos: string;
  frequency: number | null;
  core: boolean;
}

const lit = (v: unknown): string =>
  v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
const json = (v: unknown): string => (v === undefined || v === null ? 'null' : `${lit(JSON.stringify(v))}::jsonb`);

/** SQL that refreshes the built-in lexicon, keeping rows that vocab lists reference. */
export function lexiconSql(rows: LexiconRow[], batch = 500): string {
  const out = [
    '-- Generated by scripts/build-seed.ts. Do not edit by hand.',
    'begin;',
    'delete from public.lexicon where owner_id is null and id not in (select lexicon_id from public.vocab_list_items);',
    'update public.lexicon set core = false where owner_id is null;',
  ];
  for (let i = 0; i < rows.length; i += batch) {
    const values = rows
      .slice(i, i + batch)
      .map(w => `(${lit(w.headword)}, ${lit(w.lemma)}, ${lit(w.definition)}, ${lit(w.pos)}, ${lit(w.frequency)}, ${w.core ? 'true' : 'false'})`)
      .join(',\n');
    out.push(
      `insert into public.lexicon (headword, lemma, definition, pos, frequency, core) values\n${values}\non conflict (headword, pos) where owner_id is null do update set lemma = excluded.lemma, definition = excluded.definition, frequency = excluded.frequency, core = excluded.core;`,
    );
  }
  out.push('commit;', '');
  return out.join('\n');
}

function main() {
  const out: string[] = ['-- Generated by scripts/build-seed.ts. Do not edit by hand.', 'begin;'];
  MODULES.forEach((m, i) => {
    out.push(
      `insert into public.modules (id, badge, title, tagline, description, concepts, sort) values (${lit(m.id)}, ${lit(m.badge)}, ${lit(m.title)}, ${lit(m.tagline)}, ${lit(m.description)}, ${json(m.concepts)}, ${i}) on conflict (id) do update set badge = excluded.badge, title = excluded.title, tagline = excluded.tagline, description = excluded.description, concepts = excluded.concepts, sort = excluded.sort;`,
    );
    m.questions.forEach((q, pos) => {
      const answers = q.type === 'typein' ? json(q.answers) : 'null';
      const choices = q.type === 'mc' ? json(q.choices) : 'null';
      const correct = q.type === 'mc' ? lit(q.correct) : 'null';
      out.push(
        `insert into public.questions (id, module_id, position, type, badge, prompt, hint, answers, choices, correct, explanation) values (${lit(q.id)}, ${lit(m.id)}, ${pos}, ${lit(q.type)}, ${lit(q.badge)}, ${lit(q.prompt)}, ${lit(q.hint)}, ${answers}, ${choices}, ${correct}, ${lit(q.explanation)}) on conflict (id) do update set module_id = excluded.module_id, position = excluded.position, type = excluded.type, badge = excluded.badge, prompt = excluded.prompt, hint = excluded.hint, answers = excluded.answers, choices = excluded.choices, correct = excluded.correct, explanation = excluded.explanation;`,
      );
    });
  });
  out.push('commit;', '');
  writeFileSync('supabase/seed.sql', out.join('\n'));
  console.log(`seed.sql: ${MODULES.length} modules, ${MODULES.reduce((n, m) => n + m.questions.length, 0)} questions`);

  const dictline = readFileSync('content/sources/whitaker/DICTLINE.GEN', 'utf8');
  const { rows, unmatchedLodge } = composeLexicon(
    parseDooge(readFileSync('content/sources/dooge-latin-english.txt', 'utf8')),
    parseDictline(dictline),
    parseLodge(readFileSync('content/sources/lodge-core.tsv', 'utf8')),
  );
  writeFileSync('supabase/seed-lexicon.sql', lexiconSql(rows));
  console.log(`seed-lexicon.sql: ${rows.length} rows (${rows.filter(r => r.core).length} core), ${unmatchedLodge.length} unmatched Lodge lemmas`);
  if (unmatchedLodge.length) console.log(unmatchedLodge.join('\n'));

  const { verbs, unmatched } = coreTrainerVerbs(rows, parseWhitakerVerbs(dictline));
  writeFileSync('src/content/verbs.generated.ts', verbsModule(verbs));
  console.log(`verbs.generated.ts: ${verbs.length} verbs, ${unmatched.length} unmatched core verbs`);
  if (unmatched.length) console.log(unmatched.join('\n'));

  const { nouns, unmatched: unmatchedNouns } = coreNouns(rows, parseWhitakerNouns(dictline));
  writeFileSync('src/content/nouns.generated.ts', nounsModule(nouns));
  console.log(`nouns.generated.ts: ${nouns.length} nouns, ${unmatchedNouns.length} unmatched core nouns`);
  if (unmatchedNouns.length) console.log(unmatchedNouns.join('\n'));

  const { adjectives, unmatched: unmatchedAdjectives } = coreAdjectives(rows, parseWhitakerAdjectives(dictline));
  writeFileSync('src/content/adjectives.generated.ts', adjectivesModule(adjectives));
  console.log(`adjectives.generated.ts: ${adjectives.length} adjectives, ${unmatchedAdjectives.length} unmatched core adjectives`);
  if (unmatchedAdjectives.length) console.log(unmatchedAdjectives.join('\n'));
}

if (process.argv[1]?.endsWith('build-seed.ts')) main();
